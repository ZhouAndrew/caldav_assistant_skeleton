import { DOMParser } from '@xmldom/xmldom';
import { createCalDAV } from '../.build/caldav.js';
import { createWork } from '../.build/work.js';
import { projectTasks } from '../.build/tasks.js';
import assert from 'node:assert/strict';
import { createTransport } from '../.build/transport.js';
const baseUrl = process.env.CALDAV_TEST_URL;
if (!baseUrl) throw Error('Set CALDAV_TEST_URL to an isolated disposable Radicale server');
const transport = createTransport({ baseUrl, fetch, authorization: 'Basic ' + Buffer.from('test:test').toString('base64') });
await transport.request('PROPFIND', './', '<?xml version="1.0"?><d:propfind xmlns:d="DAV:"><d:prop><d:resourcetype/></d:prop></d:propfind>', { Depth: '0' });
const calendar = `transport-test-${crypto.randomUUID()}/`;
await transport.request('MKCALENDAR', calendar, '<?xml version="1.0"?><c:mkcalendar xmlns:c="urn:ietf:params:xml:ns:caldav"><d:set xmlns:d="DAV:"><d:prop><d:resourcetype><d:collection/><c:calendar/></d:resourcetype></d:prop></d:set></c:mkcalendar>');
try {
  const href = `${calendar}task.ics`;
  const text = 'BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//CalDAV Assistant transport test//EN\r\nBEGIN:VTODO\r\nUID:transport-test\r\nDTSTAMP:20261007T000000Z\r\nSUMMARY:Transport test\r\nSTATUS:NEEDS-ACTION\r\nEND:VTODO\r\nEND:VCALENDAR\r\n';
  const sameSummary = (expected, actual) => actual.includes(expected.match(/SUMMARY:[^\r\n]*/)[0]);
  const created = await transport.writeVerified(href, text, null, sameSummary);
  assert.equal(created.verified, true);
  const updated = await transport.writeVerified(href, text.replace('SUMMARY:Transport test', 'SUMMARY:Updated'), created.resource.etag, sameSummary);
  assert.notEqual(updated.resource.etag, created.resource.etag);
  await assert.rejects(transport.writeVerified(href, text, created.resource.etag, sameSummary), { code: 'Conflict' });
  assert.match((await transport.read(href)).text, /SUMMARY:Updated/);
  const client = createCalDAV(transport, baseUrl, text => new DOMParser().parseFromString(text, 'application/xml'));
  const calendars = await client.discover();
  const found = calendars.find(item => item.url.endsWith(calendar));
  assert.ok(found);
  const resources = await client.tasks(found);
  assert.equal(resources.length, 1);
  assert.equal(projectTasks(found.url, resources[0])[0].title, 'Updated');
  let pointer = null;
  const work = createWork(transport,{read:()=>pointer,publish:value=>{pointer=value;}});
  const task = projectTasks(found.url,resources[0])[0];
  await work.run('start',task,'2026-10-07T00:00:00Z','real-session-1');
  assert.ok(pointer);
  await work.run('stop',task,'2026-10-07T00:01:00Z','unused');
  assert.equal(pointer,null);
  await work.run('start',task,'2026-10-07T00:02:00Z','real-session-2');
  await work.run('complete',task,'2026-10-07T00:03:00Z','unused');
  assert.equal(pointer,null);
  assert.equal(projectTasks(found.url,await transport.read(href))[0].status,'COMPLETED');
  const cancelHref = `${calendar}cancel.ics`;
  await transport.writeVerified(cancelHref,text.replace('UID:transport-test','UID:cancel-test'),null,sameSummary);
  const cancelTask = projectTasks(found.url,await transport.read(cancelHref))[0];
  await work.run('start',cancelTask,'2026-10-07T00:04:00Z','real-cancel');
  await work.run('cancel',cancelTask,'2026-10-07T00:05:00Z','unused');
  assert.equal(pointer,null);
  assert.equal(projectTasks(found.url,await transport.read(cancelHref))[0].status,'CANCELLED');
  console.log('PASS real Radicale: canonical work start/stop/restart/complete +  create/read-back/update/read-back/stale ETag rejection/data preservation');
} finally {
  await transport.request('DELETE', calendar);
}
